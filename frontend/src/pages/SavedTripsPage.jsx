import React, { useState, useEffect } from 'react';
import { BookmarkCheck, Calendar, MapPin, Users, DollarSign, ArrowRight, Trash2, Printer, Sparkles } from 'lucide-react';
import { api } from '../api/apiClient';

export default function SavedTripsPage({ onLoadTrip, onPlanNewTrip }) {
  const [savedTrips, setSavedTrips] = useState([]);
  const [loading, setLoading] = useState(true);

  const loadSavedTrips = () => {
    setLoading(true);
    api.getSavedTrips()
      .then((data) => {
        setSavedTrips(data || []);
        setLoading(false);
      })
      .catch((err) => {
        console.error('Failed to load saved trips:', err);
        setLoading(false);
      });
  };

  useEffect(() => {
    loadSavedTrips();
  }, []);

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-10 space-y-8 animate-fadeIn">
      
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-sage/30 pb-4">
        <div>
          <div className="flex items-center gap-2 text-forest text-xs font-semibold uppercase tracking-wider mb-1">
            <BookmarkCheck className="w-4 h-4 text-forest" />
            <span>Persisted Itineraries Library</span>
          </div>
          <h1 className="font-serif-heading text-3xl sm:text-4xl font-bold text-forest">
            My Planned Itineraries
          </h1>
          <p className="text-xs text-charcoal/70">
            View, reload, or print all travel itineraries generated by the TravelSync optimization engine.
          </p>
        </div>

        <button
          onClick={onPlanNewTrip}
          className="bg-forest hover:bg-forest-600 text-ivory text-xs font-semibold px-4 py-2.5 rounded-xl shadow-soft flex items-center gap-1.5 transition-all self-start"
        >
          <Sparkles className="w-4 h-4 text-mutedLime" />
          <span>Plan a New Journey</span>
        </button>
      </div>

      {/* Content */}
      {loading ? (
        <div className="py-20 text-center space-y-2">
          <div className="w-7 h-7 rounded-full border-2 border-forest border-t-transparent animate-spin mx-auto" />
          <p className="text-xs text-charcoal/60">Loading saved itineraries from server...</p>
        </div>
      ) : savedTrips.length === 0 ? (
        <div className="bg-white p-12 rounded-3xl border border-sage/40 text-center space-y-4 max-w-xl mx-auto">
          <BookmarkCheck className="w-12 h-12 text-sage-400 mx-auto" />
          <h3 className="font-serif-heading text-xl font-bold text-forest">No Saved Itineraries Yet</h3>
          <p className="text-xs text-charcoal/60">
            You haven't generated or saved any travel plans yet. Head over to the trip planner to let the DSA engine build your first journey!
          </p>
          <button
            onClick={onPlanNewTrip}
            className="bg-forest text-ivory text-xs font-bold px-5 py-2.5 rounded-xl shadow-soft hover:bg-forest-600 transition-colors inline-flex items-center gap-2"
          >
            <Sparkles className="w-4 h-4 text-mutedLime" />
            <span>Plan My First Trip Now</span>
          </button>
        </div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
          {savedTrips.map((trip) => (
            <div
              key={trip.tripId}
              className="bg-white rounded-2xl border border-sage/40 p-6 shadow-soft hover:shadow-card hover:border-forest/50 transition-all flex flex-col justify-between space-y-5"
            >
              <div className="space-y-3">
                <div className="flex items-center justify-between">
                  <span className="text-[10px] font-bold px-2 py-0.5 rounded bg-forest text-mutedLime font-mono">
                    {trip.tripId}
                  </span>
                  <span className={`text-[10px] font-bold px-2 py-0.5 rounded ${
                    trip.feasible ? 'bg-emerald-100 text-emerald-800' : 'bg-amber-100 text-amber-800'
                  }`}>
                    {trip.feasible ? 'Feasible' : 'Alternative'}
                  </span>
                </div>

                <div>
                  <h3 className="font-serif-heading text-2xl font-bold text-forest">
                    {trip.origin} ➔ {trip.destination}
                  </h3>
                  <div className="flex items-center gap-3 text-xs text-charcoal/70 mt-1">
                    <span className="flex items-center gap-1">
                      <Calendar className="w-3.5 h-3.5 text-forest" />
                      {trip.days} Days
                    </span>
                    <span className="flex items-center gap-1">
                      <Users className="w-3.5 h-3.5 text-forest" />
                      {trip.travelers} Traveler(s)
                    </span>
                  </div>
                </div>

                <div className="p-3 rounded-xl bg-ivory/80 border border-sage/30 flex items-center justify-between text-xs font-mono">
                  <span className="text-charcoal/60">Total Cost:</span>
                  <strong className="text-forest text-sm">₹{trip.totalEstimatedCostInr?.toLocaleString()}</strong>
                </div>

                <div className="text-[11px] text-charcoal/60">
                  <strong>Stops:</strong> {trip.routeStops?.join(' ➔ ') || trip.destination}
                </div>
              </div>

              <div className="pt-3 border-t border-sage/20">
                <button
                  onClick={() => onLoadTrip(trip)}
                  className="w-full py-2.5 rounded-xl bg-forest hover:bg-forest-600 text-ivory text-xs font-bold shadow-soft flex items-center justify-center gap-1.5 transition-colors"
                >
                  <span>View Itinerary Dashboard</span>
                  <ArrowRight className="w-3.5 h-3.5 text-mutedLime" />
                </button>
              </div>
            </div>
          ))}
        </div>
      )}

    </div>
  );
}
